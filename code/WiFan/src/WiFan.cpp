void setup() {
  Serial.begin(115200);
  // Initialize the Fan pin variables as outputs
  pinMode(fan_low_output, OUTPUT);
  pinMode(fan_medium_output, OUTPUT);
  pinMode(fan_high_output, OUTPUT);
  // Ensure all outputs are set to LOW first to ensure the safety of the fan motor
  digitalWrite(fan_low_output, LOW);
  digitalWrite(fan_medium_output, LOW);
  digitalWrite(fan_high_output, LOW);

  // Initialize the power cycle pin as an output and set it to LOW to ensure the relay is not energized at startup
  pinMode(power_cycle, OUTPUT);
  digitalWrite(power_cycle, LOW);

  // First, we need to check if we're in setup mode by checking the keystore, if the setupmode key is not set, we'll assume it's the first boot and set it to true to show the setup page
  preferences.begin("wifan", true);
  if (!preferences.isKey("setupmode")) {
    // Added to address when the nvflash is blanked and there is no data in the keystore
    // We need to close the keystore before we can open it again to write to it 
    preferences.end();
    preferences.begin("wifan", false);  
    preferences.putString("setupmode", "true");
    WiFi.setHostname("WiFan");
    preferences.end();
  };
  String setupmode = preferences.getString("setupmode");

  if (setupmode == "true") {
    Serial.println("Device is in setup mode, showing configuration page");
    WiFi.mode(WIFI_AP_STA); // I was alerted that I should set the mode explicitly
    WiFi.disconnect(true); // Disconnect from any previously connected Wi-Fi networks to ensure a clean setup experience
    delay(100); 
    WiFi.scanDelete(); // Clear any previous Wi-Fi scan results to ensure we have the most up-to-date list of available networks for the user during setup
    delay(100);

    WiFi.softAPConfig(IPAddress(192, 168, 30, 1), IPAddress(192, 168, 30, 1), IPAddress(255, 255, 255, 0));
    const char* apSSID = "WiFan_Setup";
    WiFi.softAP(apSSID);
    IPAddress IP = WiFi.softAPIP();
    Serial.print("AP IP address: ");
    Serial.println(IP);

    delay(500); // Short delay to ensure the AP is fully set up before starting the Wi-Fi scan

    // Scan for usable WiFi networks
    Serial.println("Scanning for WiFi networks...");

    int n = WiFi.scanNetworks();
    std::vector<String> uniqueSSIDs;
    std::set<String> seenSSIDs;

    while (n == WIFI_SCAN_RUNNING) {
      delay(100);
      n = WiFi.scanComplete();
    }
    if ( n == WIFI_SCAN_FAILED) {
      Serial.println("WiFi scan failed");
      n = 0; // Set n to 0 to avoid issues with the rest of the code that expects n to be a number
    } else {
      Serial.println("Scan complete.");
    }

    // Filter out duplicate SSIDs from the scan results
    for (int i = 0; i < n; ++i) {
      String currentSSID = WiFi.SSID(i);

      if (seenSSIDs.find(currentSSID) == seenSSIDs.end()) {
        uniqueSSIDs.push_back(currentSSID);
        seenSSIDs.insert(currentSSID);
      }
    }

    // Store the SSIDs (up to 10) of the available networks in the AvailableNetworks array and print them to the serial console for debugging purposes
    for (int i = 0; i < uniqueSSIDs.size() && i < 10; ++i){
      String foundssid = uniqueSSIDs[i];
      foundssid.toCharArray(AvailableNetworks[i], 32);
      Serial.print("Found network: ");
      Serial.println(AvailableNetworks[i]); 
    }

    matterStarted = false; // Ensure Matter is not started in setup mode, as it requires a valid Wi-Fi connection to function properly
    matterSyncPending = false; // Ensure Matter sync is not pending in setup mode, as it requires a valid Wi-Fi connection to function properly
    // Start the DNS server for captive portal functionality, redirecting all requests to the ESP32's IP address
    dnsServer.start(53, "*", IP);
    Serial.println("DNS server started for captive portal functionality");
  } 
   else {
    // Get the Wi-Fi credentials from the keystore
    preferences.begin("wifan", true);
    String ssid = preferences.getString("configuredssid");
    String password = preferences.getString("password");
    String hostname = preferences.getString("devicename", "WiFan");
    WiFi.mode(WIFI_STA); // Set the WiFi mode to station mode for connecting to the user's Wi-Fi network
    WiFi.setHostname(hostname.c_str());
    // Connect to Wi-Fi network
    Serial.print("Connecting to ");
    Serial.println(ssid);
    WiFi.enableIPv6();
    WiFi.begin(ssid, password);
    while (WiFi.status() != WL_CONNECTED) {
      delay(500);
      Serial.print(".");
    }
    Serial.println("");
    Serial.println("WiFi connected.");
    Serial.println("IP address: ");
    Serial.println(WiFi.localIP());
    // Set up NTP for timekeeping
    const char* timezone = preferences.getString("timezone").c_str();
    configTzTime(timezone, "pool.ntp.org", "time.nist.gov", "time.google.com");
    //Initialize the Matter service for Matter over Wi-Fi/Thread functionality
    for (int i = 0; i < 3; ++i) {
      relays[i].begin(false); // Initialize each relay with the default state of OFF
      relays[i].onChange([i](bool state) {
        setOutput(i, state); // Call setOutput with the relay index and the new state when a change is detected
        return true; // Indicate that the change was handled successfully
      });
    }
    Matter.begin();
    matterStarted = true; 
    // Disable the ESP32's debug logging for the Matter service to reduce serial output clutter
    esp_log_level_set("chip[DMG]", ESP_LOG_NONE);
   }
    
    // Check to see if the device name has been changed from the default, and if not, set it to the default value of "WiFan"
    if (!preferences.isKey("devicename")) {
      // We need to close the keystore before we can open it again to write to it 
      preferences.end();
      preferences.begin("wifan", false);  
      preferences.putString("devicename", "WiFan");
      String devicename = preferences.getString("devicename");
    }

    // Check to see if the timezone has been changed from the default, and if not, set it to the default value of "PST"
    if (!preferences.isKey("timezone")) {
      // We need to close the keystore before we can open it again to write to it 
      preferences.end();
      preferences.begin("wifan", false);  
      preferences.putString("timezone", "PST");
      setTimezone("PST");
    }

    // Validate that the last state is set in the keystore, and if not, set it to the default value of "off"
    if (!preferences.isKey("laststate")) {
      // We need to close the keystore before we can open it again to write to it 
      preferences.end();
      preferences.begin("wifan", false);  
      preferences.putString("laststate", "off");
    }

    String lastmode = preferences.getString("laststate");
    // Close the keystore as a best practice to free up resources
    preferences.end();

    // Setup the redirect server to handle HTTPS requests and redirect them to the main server
    redirectServer.onNotFound(handleHTTPSRedirect);
    redirectServer.begin();
    Serial.println("Redirect server started to handle HTTPS requests"); 
    
    // Setup the catch-all for both setup mode and to handle/redirect any invalid requests
    server.onNotFound([&]() {
      if (setupmode == "true") {
        server.sendHeader("Location", "http://" + WiFi.softAPIP().toString(), true);
      } else {
        server.sendHeader("Location", "http://" + WiFi.localIP().toString(), true);
      }
      server.send(302, "text/plain", "");
    });
    
    // Set up the web server to handle different routes
    server.on("/", handleRoot);
    server.on("/config", HTTP_POST, []() {
      // Handle the form submission from the configuration page
      String ssid = server.arg("ssid");
      String password = server.arg("password");
      String device_name = server.arg("device_name");
      String timezone = server.arg("timezone");

      // Save the new configuration to the keystore
      preferences.begin("wifan", false);
      preferences.putString("configuredssid", ssid);
      preferences.putString("password", password);
      preferences.putString("devicename", device_name); // Set the new device name for network identification and 
      preferences.putString("timezone", timezone); // Set the new timezone
      preferences.putString("laststate", "off"); // Set last state to off so the motor is defaulted off on the next boot after configuration
      preferences.putString("setupmode", "false"); // Set setup mode to false after saving configuration
      preferences.end();

      // Apply the new timezone setting immediately
      setTimezone(timezone);

      // Redirect back to the root page after saving configuration
      handleRedirect("http://" + device_name + ".local");
      Reboot();
    });
    server.on("/25/on", handleGPIO25On);
    server.on("/25/off", handleGPIO25Off);
    server.on("/26/on", handleGPIO26On);
    server.on("/26/off", handleGPIO26Off);
    server.on("/27/on", handleGPIO27On);
    server.on("/27/off", handleGPIO27Off);
    server.on("/all/off", handleALLOff);
    server.on("/reset", handleResetConfirmation);
    server.on("/reset/confirm", handleReset);
    server.on("/admin", handleAdmin);
    server.on("/reboot", handleReboot);

    // Start the web server
    server.begin();
    Serial.println("HTTP server started");

    if (setupmode != "true") {
      // Check the last fan state and restore it to ensure the fan is in the correct state after a reboot or power outage
      if (lastmode == "low") {
          setSpeed(0); // Set the fan speed to LOW
          Serial.println("Restoring last state: LOW");
      } else if (lastmode == "medium") {
          setSpeed(1); // Set the fan speed to MEDIUM
          Serial.println("Restoring last state: MEDIUM");
      } else if (lastmode == "high") {
          setSpeed(2); // Set the fan speed to HIGH
          Serial.println("Restoring last state: HIGH");
      } else {
          setSpeed(-1); // Set the fan speed to OFF
          Serial.println("Restoring last state: OFF");
      }
    }
}

void loop() {
  if (matterStarted && matterSyncPending) {
    syncMatter(); // Synchronize the Matter state with the actual GPIO pin states
    matterSyncPending = false; // Reset the pending flag after synchronization
  }
  // Handle incoming client requests
  server.handleClient();
  preferences.begin("wifan", true);
  String setupmode = preferences.getString("setupmode");
  preferences.end();

  // If we're in setup mode, we also need to handle DNS requests for the captive portal functionality
  if (setupmode == "true") {
    dnsServer.processNextRequest();
  }
}